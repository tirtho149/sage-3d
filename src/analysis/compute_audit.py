"""GPU/compute audit from run logs (brief s19). Writes reports/08_gpu_compute_audit.md (+ reports/gpu_compute_audit.md copy)
and reports/gpu_scaling_estimate.md. Only measured numbers; the scaling estimate multiplies measured medians by counts."""
import json, glob, os, re, csv, statistics as st
from collections import defaultdict
R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
steps = defaultdict(list); fails = defaultdict(int); runs = defaultdict(int)
for f in glob.glob(f"{R}/results/pilot/runner_gpu*.jsonl"):
    for l in open(f):
        r = json.loads(l)
        if "sec" not in r: continue
        k = r["step"]; runs[k] += 1
        ok = r.get("rc", 0) == 0 and r.get("ok", True)
        if ok: steps[k].append(r["sec"])
        else: fails[k] += 1
for f in glob.glob(f"{R}/results/phaseA/*/ge_runs.jsonl"):
    for l in open(f):
        r = json.loads(l)
        if "sec" not in r: continue
        k = f"GE_{r['arm']}{'_frozen' if r.get('frozen_geometry') else ''}"; runs[k] += 1
        (steps[k].append(r["sec"]) if r.get("status") == "OK" else fails.__setitem__(k, fails[k] + 1))
for f in glob.glob(f"{R}/results/pilot/sam3d/*/seed*/run_meta.json"):
    m = json.load(open(f)); t = m.get("infer_s")
    if t: steps["SAM3D_reconstruction"].append(t); runs["SAM3D_reconstruction"] += 1
    if m.get("peak_vram_gb"): steps["SAM3D_peak_vram_GB(not seconds)"].append(m["peak_vram_gb"]); runs["SAM3D_peak_vram_GB(not seconds)"] += 1
for f in glob.glob(f"{R}/results/alignment/*/alignment.json"):
    steps["alignment_A0-A3"].append(json.load(open(f))["sec"]); runs["alignment_A0-A3"] += 1
for f in glob.glob(f"{R}/results/phaseA/*/[JG]/seed*/asset.ply.json"):
    steps["geometry_edit_" + f.split("/")[-3]].append(json.load(open(f))["sec"]); runs["geometry_edit_" + f.split("/")[-3]] += 1
for f in glob.glob(f"{R}/results/phaseA/**/*.png.json", recursive=True) + glob.glob(f"{R}/results/pilot/*/[BC]*/*.png.json"):
    j = json.load(open(f)); k = "IP2P_cpu" if "/phaseA/" in f else "IP2P_gpu"; steps[k].append(j["sec"]); runs[k] += 1
# GPU memory samples
mem = defaultdict(list)
p = f"{R}/results/compute/gpu_samples.csv"
if os.path.exists(p):
    for row in csv.reader(open(p)):
        try: mem[int(row[1])].append(int(row[2].strip().split()[0]))
        except Exception: pass
rows = []
for k in sorted(set(runs) | set(steps)):
    v = steps.get(k, [])
    rows.append((k, runs[k], len(v), fails[k], st.median(v) if v else None, sum(v) / 3600 if v else 0.0))
L = ["# 08 — GPU / compute audit (brief v2 §19)", "",
     "**Machine:** beast0 (local), 2× NVIDIA GTX TITAN X (Maxwell, sm_52, 12 GB). Not Nova/Slurm (user decision), so there are no Slurm job IDs.",
     "**Run identifiers:** JSONL run logs (`results/pilot/runner_gpu*.jsonl`, `results/phaseA/*/ge_runs.jsonl`) with timestamps, exit codes and verification records.", "",
     "Generated by `src/analysis/compute_audit.py` from the logs; numbers are measured, not estimated.", "",
     "| Step | attempts | successful | failed | median wall-clock (s) | total successful (GPU-h or CPU-h) |", "|---|---|---|---|---|---|"]
vram = steps.pop("SAM3D_peak_vram_GB(not seconds)", []); rows = [r for r in rows if "not seconds" not in r[0]]
for k, n, ok, fl, med, tot in rows:
    L.append(f"| {k} | {n} | {ok} | {fl} | {med:.0f} |" if med is not None else f"| {k} | {n} | {ok} | {fl} | — |")
    L[-1] += f" {tot:.2f} |"
if vram: L += ["", f"**SAM 3D peak VRAM** (from run_meta, {len(vram)} runs): median {st.median(vram):.2f} GB, max {max(vram):.2f} GB."]
L += ["", "## Notes",
      "- **Failed attempts:** caused by bugs that are now fixed. GE_F rc=1 is the colon bug (F-GE-1); GE_E/F rc=3 is the inherited `PYTORCH_CUDA_ALLOC_CONF` crash (torch 2.0.1); D_views rc=1 is the same cause. Each was retried once after its fix.",
      "- **Wasted run (not counted as a failure above):** the Peach 0006 arm E run before the fix consumed 2280 s and produced no change (F-GE-2). It is quarantined in `E_INVALID_nan_opacity_noop/`.",
      "- **IP2P timings:** IP2P on GPU is about 60 s per edit (20 steps, 512 px, fp16). IP2P on CPU is about 240 s per edit, used when both GPUs ran GaussianEditor.",
      "- **SAM 3D:** reconstruction needs the stage-wise CPU↔GPU offload to fit 12 GB, with a measured peak of 11.54 GB (`reports/phase1_protocol/04_environment.md`). That fits GPU 1 only.",
      "- **Storage (pilot + Phase A/B):** see `du` in RESEARCH_PROGRESS. Renders are stored as compressed alpha/depth (about 1 MB per 18-view set). GE checkpoints are deleted after the asset is extracted."]
if mem:
    L += ["", "## GPU memory (sampled every 30 s by `nvidia-smi`; includes all processes and the display on GPU 0)", "",
          "| GPU | samples | median MiB | max MiB |", "|---|---|---|---|"]
    for g in sorted(mem): L.append(f"| {g} | {len(mem[g])} | {st.median(mem[g]):.0f} | {max(mem[g])} |")
open(f"{R}/reports/08_gpu_compute_audit.md", "w").write("\n".join(L) + "\n")
open(f"{R}/reports/gpu_compute_audit.md", "w").write("\n".join(L) + "\n")
# scaling estimate from measured medians
med = {k: m for k, _, _, _, m, _ in rows if m}
ge = st.median([v for k in med if k.startswith("GE_") for v in steps[k]]) if any(k.startswith("GE_") for k in med) else None
sam = med.get("SAM3D_reconstruction"); ip = med.get("IP2P_gpu"); geo = st.median([v for k in med if k.startswith("geometry_edit_") for v in steps[k]]) if any(k.startswith("geometry_edit_") for k in med) else None
S = ["# GPU scaling estimate (from measured medians; local TITAN X)", "",
     f"Measured medians: SAM 3D reconstruction {sam:.0f} s; GaussianEditor 200-step run {ge:.0f} s; IP2P 2D edit {ip:.0f} s; geometry edit (incl. 18-view render) {geo:.0f} s." if all([sam, ge, ip, geo]) else "Some medians not yet available.", "",
     "Per specimen, the full arm set is: 1 reconstruction; 2D B×3, C×3, C-NG, C-MM, Bmv×8, Cmv×8, C-stage×3, I×3 = 30 IP2P; 3D E, F, K, H = 4 GE runs; J×3, G×3 = 6 geometry edits.", ""]
if all([sam, ge, ip, geo]):
    per = sam + 30 * ip + 4 * ge + 6 * geo
    S += [f"**≈ {per/3600:.1f} GPU-h per specimen** (one seed for the GE arms).", "", "| Specimens | GPU-h | wall-clock on 2 GPUs (ideal packing) |", "|---|---|---|"]
    for n in (15, 50, 150, 500):
        S.append(f"| {n} | {n*per/3600:.0f} | {n*per/3600/2:.0f} h ({n*per/3600/2/24:.1f} d) |")
    S += ["", f"GE dominates ({4*ge/per*100:.0f} % of per-specimen time) because of IP2P calls inside GE. An A100 would be several times faster, but no A100 timing was measured here, so none is claimed."]
open(f"{R}/reports/gpu_scaling_estimate.md", "w").write("\n".join(S) + "\n")
print("\n".join(L)); print("\n".join(S[2:]))
