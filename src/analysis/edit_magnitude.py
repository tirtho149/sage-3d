"""Edit magnitude next to cross-view consistency (review item A6).

An unedited asset is perfectly consistent across views, so consistency alone rewards
doing nothing. This reports HOW MUCH each arm changes the asset, relative to the
unedited render D, with the specimen as the unit (seeds averaged first, then median):
  dE_obj      mean colour change vs D over object pixels   (view_metrics.py)
  sil_change  1 - silhouette IoU vs D                      (shape change seen in renders)
  depth_chg   median |z - z_D| / rig radius                (shape change in depth)
For the single-view 2D arms, dE_in (metrics2d.csv) is the colour change inside the edit
mask, so it is not on the same footing as dE_obj (whole object) and is reported apart.

usage: ~/Desktop/Research/.venv/bin/python src/analysis/edit_magnitude.py
  -> results/statistics/edit_magnitude.json, figures/slides/edit_magnitude.tex
"""
import json
import os

import pandas as pd

R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main():
    a = pd.read_csv(f"{R}/results/statistics/arm_metrics.csv")
    sp = a.groupby(["arm", "sid"])[["dE_obj", "sil_change", "depth_change"]].mean()
    med = sp.groupby("arm").median()
    n = sp.groupby("arm").size()
    m = pd.read_csv(f"{R}/results/statistics/metrics2d.csv")
    m2 = m.groupby(["arm", "sid"])["dE_in"].mean().groupby("arm").median()
    out = {"three_d": {arm: dict(n=int(n[arm]), **{k: float(med.loc[arm, k]) for k in med.columns})
                       for arm in med.index},
           "two_d_in_mask_dE": {arm: float(v) for arm, v in m2.items()}}
    os.makedirs(f"{R}/results/statistics", exist_ok=True)
    json.dump(out, open(f"{R}/results/statistics/edit_magnitude.json", "w"), indent=1)
    M = {}
    for arm in ["E", "F", "K", "H", "J", "G"]:
        if arm in med.index:
            M[f"Mag{arm}dE"] = f"{med.loc[arm, 'dE_obj']:.1f}"
            M[f"Mag{arm}Sil"] = f"{med.loc[arm, 'sil_change']:.2f}"
    lo, hi = min(m2[["B", "C"]]), max(m2[["B", "C"]])
    M["MagTwoDdE"] = f"{lo:.0f}--{hi:.0f}"
    tex = ["% generated by src/analysis/edit_magnitude.py from results/statistics/{arm_metrics,metrics2d}.csv -- do not edit by hand"]
    tex += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in M.items()]
    os.makedirs(f"{R}/figures/slides", exist_ok=True)
    open(f"{R}/figures/slides/edit_magnitude.tex", "w").write("\n".join(tex) + "\n")
    print(json.dumps(M))


if __name__ == "__main__":
    main()
